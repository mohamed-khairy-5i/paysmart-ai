/**
 * Gemini Multimodal AI Service for Payment Receipt Verification
 * Expanded with 10 Edge Cases & Anomaly Detection
 */

const GEMINI_API_KEY = process.env.GEMINI_API_KEY || '';
const STORE_ACCOUNTS = (process.env.STORE_ACCOUNTS || '01000000000,01100000000,01012345678,store@instapay').toLowerCase().split(',');

const RECEIPT_EXTRACTION_PROMPT = `
You are an expert financial fraud detection and OCR system specializing in Egyptian and Arab electronic payment receipts (InstaPay, Vodafone Cash, Orange Money, Etisalat Cash, Telda, Bank Misr, CIB, National Bank of Egypt, and Fawry).

Carefully inspect the provided image and extract all financial details and signs of tampering.

Return a STRICT, RAW JSON object with no markdown fences, matching this exact schema:
{
  "is_valid_receipt": boolean, // true ONLY if it is an actual transfer confirmation screen/receipt
  "payment_method": string, // "InstaPay", "Vodafone Cash", "Etisalat Cash", "Orange Cash", "Bank Transfer", or "Unknown"
  "transaction_id": string, // reference number or رقم العملية / رقم المرجع
  "amount_paid": number, // exact transferred amount in numbers only, e.g. 250.00
  "currency": string, // "EGP", "USD", "SAR", etc.
  "recipient_account": string, // recipient phone number, IPA address, or account number visible on receipt
  "transfer_timestamp": string, // ISO or legible date/time on receipt if found
  "is_today_or_recent": boolean, // true if timestamp is today or recent within hours, false if days/months old
  "status_text": string, // status found on receipt, e.g. "ناجحة", "تم التحويل بنجاح", "Successful"
  "tampering_signs": {
    "detected": boolean, // true if fonts look edited, misaligned, different resolution, or Photoshopped
    "details": string // explanation if tampering is suspected
  },
  "confidence_score": number // 0.0 to 1.0 confidence in readability
}
`;

/**
 * Analyzes receipt image buffer or base64 string
 */
async function analyzeReceiptWithGemini(imageBufferOrBase64, mimeType = 'image/jpeg') {
  let base64Data = '';
  if (Buffer.isBuffer(imageBufferOrBase64)) {
    base64Data = imageBufferOrBase64.toString('base64');
  } else if (typeof imageBufferOrBase64 === 'string') {
    base64Data = imageBufferOrBase64.replace(/^data:image\/\w+;base64,/, '');
  }

  // Check if real Gemini API Key is available
  if (!GEMINI_API_KEY || GEMINI_API_KEY === 'DEMO_KEY' || GEMINI_API_KEY.trim() === '') {
    console.log('[AI Vision] No GEMINI_API_KEY provided - Running in Simulated AI Mode for testing.');
    return simulateAIAnalysis();
  }

  try {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${GEMINI_API_KEY}`;
    
    const requestBody = {
      contents: [
        {
          parts: [
            { text: RECEIPT_EXTRACTION_PROMPT },
            {
              inline_data: {
                mime_type: mimeType,
                data: base64Data
              }
            }
          ]
        }
      ],
      generationConfig: {
        temperature: 0.1,
        response_mime_type: "application/json"
      }
    };

    const response = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(requestBody)
    });

    if (!response.ok) {
      const errText = await response.text();
      console.error('[AI Vision] Gemini API error:', response.status, errText);
      throw new Error(`Gemini API error ${response.status}`);
    }

    const data = await response.json();
    const rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
    
    if (!rawText) {
      throw new Error('No response text generated by Gemini.');
    }

    const cleanJson = rawText.replace(/```json\n?/g, '').replace(/```\n?/g, '').trim();
    const parsed = JSON.parse(cleanJson);
    console.log('[AI Vision] Extracted Receipt Details:', parsed);
    return parsed;

  } catch (error) {
    console.error('[AI Vision] Fallback due to error:', error.message);
    // Escalate to human review if AI is down
    return {
      is_valid_receipt: false,
      error: error.message,
      escalate_to_human: true,
      confidence_score: 0
    };
  }
}

/**
 * Robust rule verification covering the 10 failure/edge cases
 */
function verifyReceiptRules(extractedData, targetOrder, isDuplicateTxn) {
  const result = {
    isValid: false,
    reason: '',
    code: 'FAILED',
    paidAmount: 0,
    remainingAmount: 0,
    refundAmount: 0
  };

  // Edge Case 9: AI Downtime / Network Failure
  if (extractedData.escalate_to_human) {
    result.code = 'ESCALATED_HUMAN';
    result.reason = 'تعذر فحص الإيصال آلياً في الوقت الحالي، تم تحويله للمراجعة اليدوية بواسطة الكاشير.';
    return result;
  }

  // Edge Case 7: Invalid media or unreadable screenshot
  if (!extractedData.is_valid_receipt || extractedData.confidence_score < 0.6) {
    result.code = 'INVALID_IMAGE';
    result.reason = 'الصورة المرسلة ليست إيصال دفع صحيح أو بياناتها غير واضحة المعالم.';
    return result;
  }

  // Edge Case 8: Tampering / Photoshop signs
  if (extractedData.tampering_signs && extractedData.tampering_signs.detected) {
    result.code = 'TAMPERED';
    result.reason = 'تم رصد علامات تعديل رقمي أو تلاعب في خطوط الإيصال.';
    return result;
  }

  // Edge Case 5: Anti-Replay duplicate transaction
  if (isDuplicateTxn) {
    result.code = 'DUPLICATE_TRANSACTION';
    result.reason = `رقم العملية (${extractedData.transaction_id}) تم استخدامه مسبقاً في طلب آخر. لا يمكن إعادة استخدام الإيصالات.`;
    return result;
  }

  // Edge Case 4: Expired old receipt
  if (extractedData.is_today_or_recent === false) {
    result.code = 'EXPIRED_RECEIPT';
    result.reason = 'تاريخ التحويل في الإيصال قديم ولا يطابق وقت تقديم هذا الطلب.';
    return result;
  }

  // Edge Case 6: Recipient account mismatch (if clearly visible)
  if (extractedData.recipient_account) {
    const cleanRecip = extractedData.recipient_account.toLowerCase().replace(/[^a-z0-9@]/g, '');
    const matched = STORE_ACCOUNTS.some(acc => {
      const cleanAcc = acc.replace(/[^a-z0-9@]/g, '');
      return cleanRecip.includes(cleanAcc) || cleanAcc.includes(cleanRecip);
    });

    if (!matched && cleanRecip.length > 5) {
      result.code = 'WRONG_RECIPIENT';
      result.reason = `التحويل تم لحساب (${extractedData.recipient_account}) وهو لا يطابق أي من حسابات المتجر المعتمدة.`;
      return result;
    }
  }

  // Amount comparison logic
  const paidAmount = Number(extractedData.amount_paid);
  const previouslyPaid = Number(targetOrder.amountPaidSoFar || 0);
  const totalPaid = previouslyPaid + paidAmount;
  const requiredAmount = Number(targetOrder.totalAmount);

  result.paidAmount = paidAmount;

  if (isNaN(paidAmount) || paidAmount <= 0) {
    result.code = 'UNREADABLE_AMOUNT';
    result.reason = 'تعذر قراءة المبلغ المحول بدقة من صورة الإيصال.';
    return result;
  }

  // Edge Case 2: Underpaid (Partial Payment)
  if (totalPaid < requiredAmount) {
    result.code = 'PARTIALLY_PAID';
    result.remainingAmount = requiredAmount - totalPaid;
    result.reason = `تم استلام ${paidAmount} ج.م (إجمالي المدفوع: ${totalPaid} ج.م). متبقي ${result.remainingAmount} ج.م لتأكيد الطلب.`;
    return result;
  }

  // Edge Case 3: Overpaid (Refund due)
  if (totalPaid > requiredAmount) {
    result.isValid = true;
    result.code = 'OVERPAID_CONFIRMED';
    result.refundAmount = totalPaid - requiredAmount;
    result.reason = `تم سداد ${totalPaid} ج.م بزيادة قدرها ${result.refundAmount} ج.م عن المطلوب (${requiredAmount} ج.م). سيتم اعتماد الطلب ورد الفارق نقداً.`;
    return result;
  }

  // Scenario 1: Exact Happy Path
  result.isValid = true;
  result.code = 'PAID_CONFIRMED';
  result.reason = 'تم التحقق من صحة الإيصال والمبلغ وتطابق الحساب بنجاح 100%.';
  return result;
}

